"""
PyTorch 损失计算最小 Demo
------------------------
目标：理解损失函数的作用 —— 衡量预测值与真实值之间的差距。

场景：用一条直线 y = w*x 拟合数据点 (1,2), (2,4), (3,6)
      真实关系：y = 2*x（即 w=2）
      我们随机猜一个 w，看损失有多大。
"""

import torch

# ========== 1. 准备数据 ==========
# 输入 x 和真实标签 y（3 个样本）
x = torch.tensor([1.0, 2.0, 3.0])
y = torch.tensor([2.0, 4.0, 6.0])   # 真实值：y = 2*x

# ========== 2. 初始化参数 ==========
# 随机猜测权重 w（模型要学习的参数）
w = torch.tensor([0.5], requires_grad=True)

# ========== 3. 定义损失函数 ==========
# MSE（均方误差）= 1/n * Σ(预测值 - 真实值)²
def mse_loss(y_pred, y_true):
    return ((y_pred - y_true) ** 2).mean()

# ========== 4. 前向计算：用当前 w 做预测 ==========
y_pred = w * x   # 预测值 = 0.5 * x

# ========== 5. 计算损失 ==========
loss = mse_loss(y_pred, y)

# 损失越大 → 预测越差；损失为 0 → 完美预测
## 预测值     = [0.5, 1.0, 1.5]
## 真实值     = [2.0, 4.0, 6.0]
## 验证：(0.5-2)² + (1-4)² + (1.5-6)² = 2.25 + 9 + 20.25 = 31.5，均值 31.5/3 = 10.5

print(f"当前权重 w = {w.item():.4f}")
print(f"预测值     = {y_pred.tolist()}")
print(f"真实值     = {y.tolist()}")
print(f"MSE 损失   = {loss.item():.4f}")
